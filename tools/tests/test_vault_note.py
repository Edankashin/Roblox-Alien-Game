"""Tests for tools/vault_note.py: a regenerated vault note keeps its frontmatter, a new one gets it.

Standard library only. Run:  python3 -I -m unittest discover -s tools/tests -p 'test_*.py'
(./tools/test.sh runs it too). Writes only to a temporary folder.
"""
from __future__ import annotations

import pathlib
import sys
import tempfile
import unittest

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))
import lint_vault  # noqa: E402
import vault_note  # noqa: E402

BODY = "# Remote contracts\n\nGenerated by `python3 -I tools/lint_remotes.py --write`.\n\n| a | b |\n| --- | --- |\n"
STANDARD = (
    "---\n"
    "tags: [roblox-engine, engine, generated]\n"
    "aliases: [Remote contracts]\n"
    'up: "[[Roblox-Engine]]"\n'
    "---\n"
)


class WriteNoteTests(unittest.TestCase):
    def setUp(self):
        self._tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self._tmp.cleanup)
        self.path = pathlib.Path(self._tmp.name) / "04-roblox-engine" / "Remotes.md"

    def write(self, body=BODY):
        return vault_note.write_note(self.path, body, ["roblox-engine", "engine", "generated"],
                                     aliases=["Remote contracts"], up="Roblox-Engine")

    def test_missing_frontmatter_is_added(self):
        text = self.write()
        self.assertEqual(text, STANDARD + BODY)
        self.assertEqual(self.path.read_text(encoding="utf-8"), STANDARD + BODY)

    def test_new_block_satisfies_the_vault_lint(self):
        self.write()
        found = lint_vault.FRONT.match(self.path.read_text(encoding="utf-8"))
        self.assertIsNotNone(found)
        self.assertRegex(found.group(1), r"(?m)^tags:")

    def test_existing_frontmatter_is_kept(self):
        hand_edited = '---\ntags: [roblox-engine, generated, security]\naliases: [Remotes, Net map]\nup: "[[Exploit-Review]]"\n---\n'
        self.path.parent.mkdir(parents=True)
        self.path.write_text(hand_edited + "# Old body\n\nstale\n", encoding="utf-8")
        text = self.write()
        self.assertEqual(text, hand_edited + BODY)
        self.assertEqual(self.path.read_text(encoding="utf-8"), hand_edited + BODY)

    def test_note_without_a_block_gets_one(self):
        self.path.parent.mkdir(parents=True)
        self.path.write_text("# Old body\n\nstale\n", encoding="utf-8")
        self.assertEqual(self.write(), STANDARD + BODY)

    def test_dashes_later_in_the_note_are_not_frontmatter(self):
        self.path.parent.mkdir(parents=True)
        self.path.write_text("# Old body\n\n---\ntags: [x]\n---\n", encoding="utf-8")
        self.assertEqual(self.write(), STANDARD + BODY)

    def test_second_write_is_idempotent(self):
        self.write()
        first = self.path.read_bytes()
        self.write()
        self.assertEqual(self.path.read_bytes(), first)

    def test_optional_keys_and_wrapped_up(self):
        self.assertEqual(vault_note.frontmatter(["log"]), "---\ntags: [log]\n---\n")
        self.assertEqual(vault_note.frontmatter(["log"], up="[[Log]]"), '---\ntags: [log]\nup: "[[Log]]"\n---\n')

    def test_awkward_alias_is_quoted(self):
        self.assertIn('aliases: ["Balance: two worlds", Plain name]', vault_note.frontmatter(["x"], ["Balance: two worlds", "Plain name"]))

    def test_non_ascii_body_is_written_as_utf8(self):
        body = "# Budget\n\nrate × lifetime → alive\n"
        self.write(body)
        self.assertEqual(self.path.read_bytes(), (STANDARD + body).encode("utf-8"))


if __name__ == "__main__":
    unittest.main()
