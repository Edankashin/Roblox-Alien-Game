def from_art(text: str) -> Image.Image:
    rows = [row for row in text.strip('\n').split('\n')]
    image = Image.new('RGBA', (GRID, GRID), (0, 0, 0, 0))
    for y, row in enumerate(rows[:GRID]):
        for x, char in enumerate(row[:GRID]):
            image.putpixel((x, y), PALETTE.get(char, PALETTE['.']))
    return image


def ring(radius: float, thickness: float, ticks: int = 0) -> Image.Image:
    """A ring of cells (PixelRing), or with `ticks` rune marks standing out of it (PixelRune)."""
    image = Image.new('RGBA', (GRID, GRID), (0, 0, 0, 0))
    centre = (GRID - 1) / 2
    for y in range(GRID):
        for x in range(GRID):
            d = math.hypot(x - centre, y - centre)
            if abs(d - radius) <= thickness / 2:
                lit = (x - centre) + (y - centre) < 0
                image.putpixel((x, y), PALETTE['@'] if lit else PALETTE['#'])
            elif abs(d - radius) <= thickness / 2 + 0.7:
                image.putpixel((x, y), PALETTE[':'])
    for index in range(ticks):
        angle = math.tau * index / ticks
        for step in (radius - 1.6, radius + 1.6):
            x = round(centre + math.cos(angle) * step)
            y = round(centre + math.sin(angle) * step)
            if 0 <= x < GRID and 0 <= y < GRID:
                image.putpixel((x, y), PALETTE['+'])
    return image


def halo() -> Image.Image:
    """A soft square-stepped glow (PixelHalo, the aura): alpha falls in whole steps from the middle, so it reads as blocks."""
    image = Image.new('RGBA', (GRID, GRID), (0, 0, 0, 0))
    centre = (GRID - 1) / 2
    for y in range(GRID):
        for x in range(GRID):
            d = max(abs(x - centre), abs(y - centre)) * 0.6 + math.hypot(x - centre, y - centre) * 0.4
            level = int(d // 1.6)
            alpha = (170, 130, 95, 60, 30, 0)[min(level, 5)]
            if alpha:
                image.putpixel((x, y), (255, 255, 255, alpha))
    return image


def sheet(frames: "list[Image.Image]") -> Image.Image:
    """A 2 x 2 flipbook of four 16-cell frames (Grid2x2), left to right, top to bottom."""
    out = Image.new('RGBA', (GRID * 2, GRID * 2), (0, 0, 0, 0))
    for index, frame in enumerate(frames[:4]):
        out.paste(frame, ((index % 2) * GRID, (index // 2) * GRID))
    return out


def twinkle_frame(arm: int) -> Image.Image:
    image = Image.new('RGBA', (GRID, GRID), (0, 0, 0, 0))
    c = GRID // 2 - 1
    for dx in (0, 1):
        for dy in (0, 1):
            image.putpixel((c + dx, c + dy), PALETTE['@'])
    for step in range(1, arm + 1):
        tone = PALETTE['#'] if step < arm else PALETTE['o']
        for x, y in ((c - step, c), (c + 1 + step, c + 1), (c, c - step), (c + 1, c + 1 + step)):
            image.putpixel((x, y), tone)
        if step <= arm // 2:
            for x, y in ((c - step, c + 1), (c + 1 + step, c), (c + 1, c - step), (c, c + 1 + step)):
                image.putpixel((x, y), PALETTE['+'])
    return image


def ember_frame(index: int) -> Image.Image:
    base = from_art(ART['PixelEmber'])
    if index % 2 == 1:  # a flicker: the tip cell goes out and a side cell lights
        base.putpixel((7, 2), PALETTE['.'])
        base.putpixel((10, 6), PALETTE['@'])
    if index >= 2:  # the lower frames sink a cell
        shifted = Image.new('RGBA', (GRID, GRID), (0, 0, 0, 0))
        shifted.paste(base, (0, 1))
        base = shifted
    return base


def sprites() -> "dict[str, Image.Image]":
    """Every sprite at cell size (16 x 16, or 32 x 32 for a sheet)."""
    out = {key: from_art(text) for key, text in ART.items()}
    out['PixelRing'] = ring(6.0, 1.2)
    out['PixelRune'] = ring(5.6, 1.0, ticks=8)
    out['PixelHalo'] = halo()
    out['PixelTwinkle'] = sheet([twinkle_frame(arm) for arm in (1, 3, 6, 3)])
    out['PixelEmberFlicker'] = sheet([ember_frame(index) for index in range(4)])
    return dict(sorted(out.items()))


def upscale(image: Image.Image) -> Image.Image:
    return image.resize((image.width * SCALE, image.height * SCALE), Image.NEAREST)


def tint(image: Image.Image, color: "tuple[int, int, int]") -> Image.Image:
    """The sprite as an emitter draws it: its grey times the emitter's Color, its alpha kept."""
    out = Image.new('RGBA', image.size)
    src, dst = image.load(), out.load()
    for y in range(image.height):
        for x in range(image.width):
            r, _, _, a = src[x, y]
            dst[x, y] = (color[0] * r // 255, color[1] * r // 255, color[2] * r // 255, a)
    return out


def contact_sheet(images: "dict[str, Image.Image]", path: Path) -> None:
    """Every sprite on a dark tile tinted warm and a light tile tinted cool, with its key (a sheet shows its four frames)."""
    tile = 96
    columns = 7
    names = list(images)
    rows = math.ceil(len(names) / columns)
    out = Image.new('RGB', (columns * tile * 2, rows * (tile + 18)), (24, 24, 32))
    draw = ImageDraw.Draw(out)
    for index, name in enumerate(names):
        image = upscale(images[name]).resize((64, 64), Image.NEAREST)
        x0 = (index % columns) * tile * 2
        y0 = (index // columns) * (tile + 18)
        for half, (ground, color) in enumerate((((30, 28, 48), (255, 214, 110)), ((206, 226, 236), (60, 130, 230)))):
            box = (x0 + half * tile, y0, x0 + half * tile + tile, y0 + tile)
            draw.rectangle(box, fill=ground)
            body = tint(image, color)
            out.paste(body, (box[0] + (tile - 64) // 2, box[1] + (tile - 64) // 2), body)
        draw.text((x0 + 4, y0 + tile + 3), name, fill=(230, 230, 236))
    out.save(path)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--out', type=Path, default=OUT, help='folder for the PNGs (default assets/sprites/blocky)')
    parser.add_argument('--sheet', type=Path, help='also write a labelled contact sheet here')
    args = parser.parse_args()
    args.out.mkdir(parents=True, exist_ok=True)
    images = sprites()
    for name, image in images.items():
        upscale(image).save(args.out / f'{name}.png')
    print(f'pixel sprites: {len(images)} written to {args.out}')
    if args.sheet:
        contact_sheet(images, args.sheet)
        print(f'contact sheet: {args.sheet}')


if __name__ == '__main__':
    main()
