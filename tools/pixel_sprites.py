#!/usr/bin/env python3
"""The block-cell particle sprites (B44: every surface is little blocks) for data/Effects.

Each sprite is drawn on a 16 x 16 cell grid and written 4x up with nearest-neighbour scaling (64 x 64 px), so every cell is a
crisp 4 px square even where Roblox filters the texture. Sprites are white and greys on transparency: a ParticleEmitter's
Color tints them, so one sprite serves every species, and the greys keep the cell shading (a lit top-left cell, a darker
lower-right one, one step apart like the creature cells of Blocky-Style C3). Two are flipbook sheets, 2 x 2 frames of 64 px
(128 x 128): PixelTwinkle (a star that opens and closes) and PixelEmberFlicker (an ember that flickers), played by
data/Effects.Sheets once uploaded.

The keys match Icons.Particles (Pixel...). Nothing here uploads: the PNGs go to assets/sprites/blocky, and the ids stay 0 until
the Mac uploads them from there (Decision B47: tools/finalize_upload.sh, which runs tools/upload_assets.py --blocky and fills
Icons.luau).

    python3 -I tools/pixel_sprites.py                 # writes assets/sprites/blocky/*.png
    python3 -I tools/pixel_sprites.py --sheet out.png # also a labelled contact sheet of all of them, on dark and light
"""
